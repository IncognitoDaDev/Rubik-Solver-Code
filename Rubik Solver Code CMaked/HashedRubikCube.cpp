#include "HashedRubikCube.h"

void HashedRubikCube::action(int move)
{
	switch (move)
	{
	case 0: rotateFace(Up, false, false); break;
	case 1: rotateFace(Down, false, false); break;
	case 2: rotateFace(Front, false, false); break;
	case 3: rotateFace(Back, false, false); break;
	case 4: rotateFace(Right, false, false); break;
	case 5: rotateFace(Left, false, false); break;
	case 6: rotateFace(Up, true, false); break;
	case 7: rotateFace(Down, true, false); break;
	case 8: rotateFace(Front, true, false); break;
	case 9: rotateFace(Back, true, false); break;
	case 10: rotateFace(Right, true, false); break;
	case 11: rotateFace(Left, true, false); break;
	case 12: rotateFace(Up, false, true); break;
	case 13: rotateFace(Down, false, true); break;
	case 14: rotateFace(Front, false, true); break;
	case 15: rotateFace(Back, false, true); break;
	case 16: rotateFace(Right, false, true); break;
	case 17: rotateFace(Left, false, true); break;
	}
}

void HashedRubikCube::undo()
{
	if (oldMove > 11) action(oldMove);
	else if (oldMove > 5) action(oldMove - 6);
	else action(oldMove + 6);
}

